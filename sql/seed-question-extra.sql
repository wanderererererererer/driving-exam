-- 科目一题目总数（应为 36 → 顺序练习每页 20，共 2 页）
SELECT COUNT(*) AS total_questions FROM question
 WHERE subject_code = 'SUBJECT_1' AND status = 1 AND deleted = 0;

-- 各知识点直接题目数 + 含子孙合计
SELECT kp.id, kp.name, kp.parent_id,
       SUM(CASE WHEN q.id IS NOT NULL THEN 1 ELSE 0 END) AS direct_cnt
  FROM knowledge_point kp
  LEFT JOIN question q ON q.knowledge_point_id = kp.id
   AND q.subject_code = 'SUBJECT_1' AND q.status = 1 AND q.deleted = 0
 WHERE kp.subject_code = 'SUBJECT_1' AND kp.deleted = 0
 GROUP BY kp.id, kp.name, kp.parent_id
 ORDER BY kp.id;
