-- 知识点树（含子孙题目数合计：id=1 应为 10，id=4 应为 8）
SELECT kp.id, kp.name, kp.parent_id, COUNT(q.id) AS question_cnt
  FROM knowledge_point kp
  LEFT JOIN question q ON q.knowledge_point_id = kp.id
   AND q.subject_code = 'SUBJECT_1' AND q.deleted = 0 AND q.status = 1
 WHERE kp.subject_code = 'SUBJECT_1' AND kp.deleted = 0
 GROUP BY kp.id, kp.name, kp.parent_id
 ORDER BY kp.id;
